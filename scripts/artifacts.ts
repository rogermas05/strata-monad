import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import type { Abi, Hex } from "viem";
const sources: Record<string, string> = {
  OptionsEngine: "OptionsEngine.sol",
  OptionToken: "OptionsEngine.sol",
  DemoUSDC: "TestAssets.sol",
  WrappedMON: "TestAssets.sol",
  DemoOracle: "Oracle.sol",
  PythExpiryOracle: "Oracle.sol",
  PythSessionCloseOracle: "Oracle.sol",
  DemoSessionOracle: "Oracle.sol",
  OracleRouter: "Oracle.sol",
  DemoOrderBook: "Venues.sol",
  StrategyRouter: "Venues.sol",
  KuruExactAdapter: "Venues.sol",
  HouseVault: "HouseVault.sol",
  StrataToken: "Strata.sol",
  StrataStaking: "Strata.sol",
  StrataDistributor: "Strata.sol",
};
export function artifact(name: string): { abi: Abi; bytecode: Hex } {
  const a = JSON.parse(
    readFileSync(
      new URL(
        `../contracts/out/${sources[name]}/${name}.json`,
        import.meta.url,
      ),
      "utf8",
    ),
  );
  return { abi: a.abi, bytecode: a.bytecode.object };
}
export function exportAbis() {
  mkdirSync(new URL("../packages/core/src/generated", import.meta.url), {
    recursive: true,
  });
  for (const name of Object.keys(sources))
    writeFileSync(
      new URL(`../packages/core/src/generated/${name}.json`, import.meta.url),
      JSON.stringify(artifact(name).abi, null, 2) + "\n",
    );
  writeFileSync(
    new URL("../packages/core/src/generated/contracts.ts", import.meta.url),
    "// Generated by scripts/artifacts.ts; use these exports in ESM runtimes.\n" +
      Object.keys(sources)
        .sort()
        .map(
          (name) =>
            `export const ${name} = ${JSON.stringify(artifact(name).abi)};`,
        )
        .join("\n") +
      "\n",
  );
}
